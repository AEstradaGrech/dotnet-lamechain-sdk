using System.Text.Json;

namespace Dotnet.OllamaSharp.LameChain.SDK.Infrastructure.Models.Coding
{
    public sealed record PythonError(string Type, string Message, string Traceback);
    public sealed record PythonArtifact(string Path, long SizeBytes);

    // A pip requirement accepted by the dependency policy: Name ("pandas") and the full Requirement passed to uv ("pandas>=2")
    public sealed record PythonDependency(string Name, string Requirement);

    // Raw output of a launched process (uv, python...). ExitCode is null when the process was killed by timeout
    public sealed record ProcessResult(int? ExitCode, string Stdout, string Stderr, bool TimedOut);

    // Known malicious packages check. Error != null means the check could not be done (service unreachable...)
    public sealed record MaliciousPackage(string Name, IReadOnlyList<string> AdvisoryIds);
    public sealed record MaliciousPackageReport(IReadOnlyList<MaliciousPackage> Malicious, string? Error);

    public sealed record PythonExecutionResults
    {
        public bool Success { get; init; }
        public JsonElement? Result { get; init; }   // JSON result of the execution, if any. It can be null if the code does not return anything or if there was an error.
        public string? ResultType { get; init; }    // hint for the LLM not for the deserializer
        public string Stdout { get; init; } = "";
        public string Stderr { get; init; } = "";
        public PythonError? Error { get; init; }    // Type: InputError | DependencyError | MaliciousPackage | LauncherError | Timeout | HarnessFailure | <python exception name>
        public List<PythonArtifact> Artifacts { get; init; } = []; // List of artifacts generated by the execution, if any (the process may return nothing).
        public long DurationMs { get; init; }
        // Executor params
        public bool TimedOut { get; init; }
        public int? ExitCode { get; init; }
    }
}
